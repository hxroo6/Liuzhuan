package com.liuzhuan.checks

import com.liuzhuan.app.MaterialLibrary
import com.liuzhuan.app.data.MaterialRepository
import com.liuzhuan.app.data.toMaterialItem
import com.liuzhuan.app.net.*
import kotlinx.coroutines.*
import org.json.JSONObject
import org.json.JSONArray
import java.io.File

private var checks=0
private fun verify(ok:Boolean,label:String){check(ok){label};checks++;println("PASS $label")}
private suspend fun settled(predicate:()->Boolean){withTimeout(10000){while(!predicate())delay(20)}}
fun main(args:Array<String>)=runBlocking {
    try {
        val proof=JSONObject(File(args[0]).readText())
        fun valid(p:String=proof.getString("proof"),nonce:String=proof.getString("nonce"),port:Int=proof.getInt("port"),name:String=proof.getString("name"))=
            IdentityProof.verify(proof.getString("auth"),nonce,proof.getString("id"),port,name,p)
        verify(valid(),"Android verifies proof generated by production C# identity code")
        verify(!valid(nonce="a".repeat(32)),"different challenge rejected")
        verify(!valid(port=12345),"port modification rejected")
        verify(!valid(name="dGFtcGVyZWQ="),"name modification rejected")
        verify(!valid(p="z".repeat(64)),"malformed proof rejected without crash")
        val socket=java.net.DatagramSocket(0,java.net.InetAddress.getByName("127.0.0.1"))
        val discoveryPort=socket.localPort
        val responder=launch(Dispatchers.IO) { socket.use { udp -> repeat(2) {
            val packet=java.net.DatagramPacket(ByteArray(1024),1024);udp.receive(packet)
            val message=String(packet.data,0,packet.length,Charsets.UTF_8)
            val reply=if(message.startsWith("LIUZHUAN_DISCOVER_V2|")) {
                val nonce=message.substringAfter('|');val id=proof.getString("id");val name=proof.getString("name")
                val mac=javax.crypto.Mac.getInstance("HmacSHA256").apply{init(javax.crypto.spec.SecretKeySpec(proof.getString("auth").toByteArray(),"HmacSHA256"))}
                val digest=mac.doFinal("LZ-ID-1|$nonce|$id|8899|$name".toByteArray()).joinToString(""){"%02x".format(it)}
                "LIUZHUAN_OFFER_V2|$id|8899|$name|$nonce|$digest"
            } else "LIUZHUAN_OFFER|203.0.113.1|8899|Legacy fixture"
            val bytes=reply.toByteArray();udp.send(java.net.DatagramPacket(bytes,bytes.size,packet.address,packet.port))
        }}}
        val discovered=LanDiscovery.discoverAt(400,"127.0.0.1",discoveryPort);responder.join()
        verify(discovered.size==1 && discovered.single().deviceId==proof.getString("id"),"v2 offer replaces legacy address hint without duplicate device")
        verify(discovered.single().verified(proof.getString("auth")),"actual UDP response verified with current fresh nonce")
        verify(discovered.single().ip=="127.0.0.1","actual packet source used instead of untrusted advertised address")
        val items=(0 until 250).map {i->JSONObject().put("id","fixture-$i").put("type","Text").put("name",if(i==249)"deep fixture" else "Fixture $i")
            .put("addedTime",1000L+i).put("size",0).put("revision",3).put("sourceRevision",7).put("favorite",i%2==0).put("source","Android").put("sourceDevice","Fixture phone").put("group","Fixtures").put("tags",JSONArray(listOf("tag"))).put("note","note")}
        var slow=false;var edits=0;var calls=0
        val c=LanClient("fixture-library"){q->
            calls++;if(slow)delay(300)
            if(q.optString("action")=="edit") {
                edits++
                if(q.optLong("revision")!=3L)JSONObject().put("error","conflict").put("code","conflict").put("item",items[0])
                else JSONObject().put("libraryId","fixture-library").put("item",items[0])
            }else {
                val rows=items.filter {it.optString("name").contains(q.optString("search"),true)}
                val offset=q.optInt("offset");val page=rows.drop(offset).take(100)
                JSONObject().put("libraryId","fixture-library").put("sequence",1000).put("items",JSONArray().apply{page.forEach {put(it)}})
                    .put("total",rows.size).put("nextOffset",minOf(offset+100,rows.size)).put("groups",JSONArray(listOf("Fixtures"))).put("tags",JSONArray(listOf("tag")))
            }
        }
        MaterialLibrary.connected(c,"computer:library")
        settled{!MaterialLibrary.state.value.loading && MaterialRepository.materials.value.size==100}
        verify(MaterialLibrary.state.value.total==250,"complete library count negotiated beyond legacy 50")
        MaterialLibrary.loadMore();settled{!MaterialLibrary.state.value.loading && MaterialRepository.materials.value.size==200}
        MaterialLibrary.loadMore();settled{!MaterialLibrary.state.value.loading && MaterialRepository.materials.value.size==250}
        verify(!MaterialLibrary.state.value.hasMore && MaterialRepository.materials.value.map {it.id}.distinct().size==250,"bounded pages append without duplicate IDs")
        val sample=MaterialRepository.materials.value.first {it.id=="fixture-0"}
        verify(sample.revision==3L && sample.favorite && sample.group=="Fixtures" && sample.tags==listOf("tag") && sample.note=="note" && sample.sourceDevice=="Fixture phone","complete metadata decoded from production protocol")
        verify(sample.sourceRevision==7L&&Proto.parseItemAdded(items[0]).toMaterialItem().sourceRevision==7L,"list and delta codecs retain source content version independently of metadata revision")
        MaterialLibrary.query(MaterialLibrary.Query(search="deep"));settled{!MaterialLibrary.state.value.loading && MaterialRepository.materials.value.size==1}
        verify(MaterialRepository.materials.value.single().id=="fixture-249","query sent to server, older unloaded item found")
        slow=true
        MaterialLibrary.query(MaterialLibrary.Query(search="Fixture 1"));delay(280)
        MaterialLibrary.query(MaterialLibrary.Query(search="deep"));settled{!MaterialLibrary.state.value.loading && MaterialRepository.materials.value.size==1}
        verify(MaterialRepository.materials.value.single().id=="fixture-249","late previous search cannot replace current results")
        slow=false
        val conflict=MaterialLibrary.edit(sample.copy(revision=0),false,"",emptyList(),"draft")
        verify(conflict.optString("code")=="conflict" && edits==1,"conflict preserved for explicit draft resolution")
        val sent=MaterialLibrary.edit(sample,false,"",emptyList(),"draft")
        verify(sent.optString("error").isEmpty() && edits==2,"explicit edit retains revision and current computer binding")
        settled{!MaterialLibrary.state.value.loading}
        MaterialLibrary.disconnected();verify(!MaterialLibrary.state.value.connected,"disconnect makes retained summaries read-only")
        verify(runCatching{MaterialLibrary.edit(sample,false,"",emptyList(),"")}.isFailure,"offline edit rejected")
        val newClient=LanClient("new-library"){JSONObject().put("libraryId","new-library").put("sequence",0).put("total",0).put("nextOffset",0).put("items",JSONArray())}
        MaterialLibrary.connected(newClient,"other-computer:new-library")
        verify(MaterialRepository.materials.value.isEmpty(),"different authenticated library clears previous material mirror")
        settled{!MaterialLibrary.state.value.loading}
        val original=Proto.parseItemAdded(items[0].put("sequence",1)).toMaterialItem();val next=Proto.parseItemAdded(items[1].put("sequence",1)).toMaterialItem()
        MaterialRepository.replaceAll(listOf(original,next),1)
        val order=MaterialRepository.materials.value.map{it.id}
        MaterialRepository.update(original.copy(note="updated",sequence=2))
        verify(MaterialRepository.materials.value.map{it.id}==order && MaterialRepository.materials.value.first{it.id==original.id}.note=="updated","metadata delta updates in place without moving item")
        val countBefore=calls;delay(500);verify(calls==countBefore,"no idle page polling")
        val large=LanClient("large-library"){q->
            val start=q.optInt("offset");val end=minOf(start+100,50000)
            JSONObject().put("libraryId","large-library").put("sequence",1).put("total",50000).put("nextOffset",end)
                .put("items",JSONArray().apply{(start until end).forEach {i->put(JSONObject().put("id","large-$i").put("type","Text").put("name","Large $i").put("addedTime",50000-i))}})
        }
        MaterialLibrary.connected(large,"large-library");settled{!MaterialLibrary.state.value.loading}
        repeat(12){MaterialLibrary.loadMore();settled{!MaterialLibrary.state.value.loading}}
        verify(MaterialRepository.materials.value.size==1000&&MaterialLibrary.firstRetainedOffset()==300&&MaterialRepository.materials.value.map{it.id}.distinct().size==1000,
            "1300 paged results retain exactly the correct 1000-row window without duplicates (rows=${MaterialRepository.materials.value.size}, offset=${MaterialLibrary.firstRetainedOffset()}, error=${MaterialLibrary.state.value.error})")
        MaterialLibrary.latest();settled{!MaterialLibrary.state.value.loading}
        verify(MaterialLibrary.firstRetainedOffset()==0&&MaterialRepository.materials.value.any {it.id=="large-0"},"bounded browsing can return to the newest window")
        MaterialRepository.add(sample.copy(id="live-new",time=999999,sequence=2))
        verify(MaterialRepository.materials.value.size==1000&&MaterialRepository.materials.value.first().id=="live-new","live deltas obey the same retained-summary budget before a refresh")
        println("PASS $checks Android identity/library checks; production state machine with substitute transport")
    }catch(t:Throwable){t.printStackTrace();kotlin.system.exitProcess(1)}
}
